import fs from 'node:fs';import assert from 'node:assert/strict';
const a=fs.readFileSync('app.js','utf8'),h=fs.readFileSync('index.html','utf8');
const v=(a.match(/const APP_VERSION='([^']+)'/)||[])[1];
const n=Number((v.match(/rc4\.(\d+)/)||[])[1]);
assert.ok(n>=181,'requires rc4.181+');
assert.ok(h.includes(v),'index/app version mismatch');
const marker=a.indexOf("seasonLiveStateAge.textContent='JS gestartet'");
const boot=a.indexOf('const rosterResult=await bootstrapSeasonWorkspace();',marker);
assert.ok(marker>=0&&boot>marker,'persistent pre-network JS execution marker missing or ordered incorrectly');
const reassert=a.lastIndexOf("seasonLiveStateAge.textContent='JS gestartet'",boot);
assert.ok(reassert>=marker&&reassert<boot,'execution marker not present after shared startup renderers');
assert.ok(a.includes('const SEASON_BOOTSTRAP_WATCHDOG_MS=26000'),'bounded startup watchdog missing');
assert.ok(a.includes("Season Auto-Sync FAIL-CLOSED · Startup-Watchdog"),'roster watchdog fail-closed UI missing');
assert.ok(a.includes("Kader-Aktualisierung fehlgeschlagen · Startup-Watchdog"),'live-state watchdog failure UI missing');
assert.ok(a.includes('seasonBootstrapWatchdogClear(bootstrapWatchdogToken)'),'watchdog cleanup missing');
assert.ok(a.includes("if(els.expertSearch&&els.expertsList)renderExperts();"),'removed Draft expert DOM still required by startup');
assert.ok(a.includes("if(els.decisionLog)renderLog();"),'removed Draft decision-log DOM still required by startup');
assert.ok(a.includes("if(els.autoRefresh?.checked)"),'removed Draft auto-refresh DOM still required by startup');
console.log('SEASON_STARTUP_EXECUTION_WATCHDOG_PASS '+v);
